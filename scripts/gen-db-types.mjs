#!/usr/bin/env node
// Regenerates the Database types from the linked Supabase project, keeping only
// pe_-prefixed tables/functions/enums (the Postgres instance is shared with other
// apps). Writes src/lib/types/database.types.ts; the edge function uses an
// untyped client today, so no mirror copy under supabase/functions/_shared yet.
// Usage: npm run gen:db-types
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PREFIX = 'pe_';
const OUTPUTS = [join(root, 'src/lib/types/database.types.ts')];

const raw = execFileSync(
	'npx',
	['supabase', 'gen', 'types', 'typescript', '--linked', '--schema', 'public'],
	{ encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, cwd: root }
);

const lines = raw.split('\n');

// Entries in the generated sections all start at exactly 6-space indent with an
// identifier; deeper-indented lines (and 6-space closers like `      }`) belong
// to the entry above. Grouping on that boundary handles braces, brackets and
// multi-line enum unions uniformly.
const ENTRY_START = /^ {6}(\w+):/;
const SECTION_CLOSE = /^ {4}\},?$/;

let cursor = 0;

function filterNextSection(headerRegex, emptyFiller, keep = (name) => name.startsWith(PREFIX)) {
	let start = -1;
	for (let i = cursor; i < lines.length; i++) {
		if (headerRegex.test(lines[i])) {
			start = i;
			break;
		}
	}
	if (start === -1) throw new Error(`section not found: ${headerRegex}`);
	let end = -1;
	for (let i = start + 1; i < lines.length; i++) {
		if (SECTION_CLOSE.test(lines[i])) {
			end = i;
			break;
		}
	}
	if (end === -1) throw new Error(`section close not found: ${headerRegex}`);

	const kept = [];
	let keepCurrent = false;
	for (let i = start + 1; i < end; i++) {
		const m = lines[i].match(ENTRY_START);
		if (m) keepCurrent = keep(m[1]);
		if (keepCurrent) kept.push(lines[i]);
	}
	if (kept.length === 0 && emptyFiller) kept.push(emptyFiller);
	lines.splice(start + 1, end - start - 1, ...kept);
	cursor = start + 1 + kept.length;
}

// Document order: Database.public.{Tables, Functions, Enums}, then Constants.public.Enums.
filterNextSection(/^ {4}Tables: \{$/, '      [_ in never]: never');
filterNextSection(/^ {4}Functions: \{$/, '      [_ in never]: never');

// Enums are kept when prefixed or when a kept table/function column refers to
// them (e.g. package_type_enum), so the filtered file stays self-contained.
const referencedEnums = new Set(
	lines
		.slice(0, cursor)
		.flatMap((line) => [...line.matchAll(/\["Enums"\]\["(\w+)"\]/g)].map((m) => m[1]))
);
const keepEnum = (name) => name.startsWith(PREFIX) || referencedEnums.has(name);
filterNextSection(/^ {4}Enums: \{$/, '      [_ in never]: never', keepEnum);
filterNextSection(/^ {4}Enums: \{$/, null, keepEnum);

const banner =
	'// Generated by scripts/gen-db-types.mjs — do not edit by hand.\n' +
	'// Filtered to pe_-prefixed objects; regenerate with: npm run gen:db-types\n\n';
const output = banner + lines.join('\n');

for (const path of OUTPUTS) writeFileSync(path, output);
execFileSync('npx', ['prettier', '--write', ...OUTPUTS], { cwd: root, stdio: 'inherit' });
console.log(`Wrote ${OUTPUTS.join(' and ')}`);
